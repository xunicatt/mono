#define PIN_IN_FLT(port, pin) \
do {                          \
    GPIO_DDR(port) &= ~(pin); \
    GPIO_CR1(port) &= ~(pin); \
    GPIO_CR2(port) &= ~(pin); \
} while (0)

#define PIN_IN_FLT_IT(port, pin) \
do {                             \
    GPIO_DDR(port) &= ~(pin);    \
    GPIO_CR1(port) &= ~(pin);    \
    GPIO_CR2(port) |= (pin);     \
} while (0)

#define PIN_IN_PU(port, pin)  \
do {                          \
    GPIO_DDR(port) &= ~(pin); \
    GPIO_CR1(port) |= (pin);  \
    GPIO_CR2(port) &= ~(pin); \
} while (0)

#define PIN_IN_PU_IT(port, pin) \
do {                            \
    GPIO_DDR(port) &= ~(pin);   \
    GPIO_CR1(port) |= (pin);    \
    GPIO_CR2(port) |= (pin);    \
} while (0)

#define PIN_OUT_OD(port, pin) \
do {                          \
    GPIO_DDR(port) |= (pin);  \
    GPIO_CR1(port) &= ~(pin); \
    GPIO_CR2(port) &= ~(pin); \
} while (0)

#define PIN_OUT_OD_FAST(port, pin) \
do {                               \
    GPIO_DDR(port) |= (pin);       \
    GPIO_CR1(port) &= ~(pin);      \
    GPIO_CR2(port) |= (pin);       \
} while (0)

#define PIN_OUT_PP(port, pin) \
do {                          \
    GPIO_DDR(port) |= (pin);  \
    GPIO_CR1(port) |= (pin);  \
    GPIO_CR2(port) &= ~(pin); \
} while (0)

#define PIN_OUT_PP_FAST(port, pin) \
do {                               \
    GPIO_DDR(port) |= (pin);       \
    GPIO_CR1(port) |= (pin);       \
    GPIO_CR2(port) |= (pin);       \
} while (0)

#define PIN_SET(port, pin) GPIO_ODR(port) |= (pin)
#define PIN_RESET(port, pin) GPIO_ODR(port) &= ~(pin)
#define PIN_GET(port, pin) ((GPIO_IDR(port) & (pin)) != 0)
#define PIN_DEFAULT PIN_IN_FLT

